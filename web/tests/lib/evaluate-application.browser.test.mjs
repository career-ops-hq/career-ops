import { liveServerSkip } from '../helpers/live-server.mjs';
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { persistEvaluation } from '../../src/lib/report-persist.mjs';
import { evaluationState, stampEvaluationScope } from '../../src/lib/evaluation-state.mjs';
import { FULL_EVALUATION } from '../../src/lib/evaluation-options.mjs';
import { resolveColumns, parseTrackerRow } from '../../../tracker-parse.mjs';

const codeRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const report = (company, url) => `# Evaluation: ${company} — Engineer\n\n**URL:** ${url}\n\n## Machine Summary\n\`\`\`yaml\ncompany: ${company}\nrole: Engineer\nscore: 4.2\n\`\`\`\n\n## B) Match with CV\nFictional evidence.\n\n## Job Description (archived verbatim)\nFictional job description.\n`;

test('evaluate a skipped job and complete a partial report from tracker/detail, using fictional AI output and real persistence', {
  skip: liveServerSkip('EVALUATE_APPLICATION_TEST_URL', 'EVALUATE_APPLICATION_TEST_ROOT'), timeout: 120000,
}, async t => {
  const origin = new URL(process.env.EVALUATE_APPLICATION_TEST_URL);
  assert.ok(['localhost', '127.0.0.1'].includes(origin.hostname));
  const root = fs.realpathSync(process.env.EVALUATE_APPLICATION_TEST_ROOT);
  const relative = path.relative(fs.realpathSync(os.tmpdir()), root);
  assert.ok(relative && !relative.startsWith('..') && !path.isAbsolute(relative));
  assert.equal(fs.readFileSync(path.join(root, '.evaluation-fixture'), 'utf8').trim(), 'fictional-only');
  fs.mkdirSync(path.join(root, 'data'), { recursive: true });
  fs.mkdirSync(path.join(root, 'reports'), { recursive: true });
  const file = path.join(root, 'data/applications.md');
  const original = stampEvaluationScope(report('Fixture Partial', 'https://fixture.example/22'), ['summary']);
  fs.writeFileSync(path.join(root, 'reports/044-partial-2026-10-28.md'), original);
  fs.writeFileSync(file, '# Applications\n\n| # | Date | Company | Role | Score | Status | PDF | Report | Notes | URL |\n|---|---|---|---|---|---|---|---|---|---|\n| 11 | 2026-10-28 | Fixture Skip | Engineer | — | SKIP | ❌ | — | Keep skipped note | https://fixture.example/11 |\n| 22 | 2026-10-28 | Fixture Partial | Engineer | 4.2/5 | Applied | ❌ | [044](../reports/044-partial-2026-10-28.md) | Keep partial note | https://fixture.example/22 |\n');
  fs.writeFileSync(path.join(root, 'data/pipeline.md'), '- [x] https://fixture.example/11 | Fixture Skip | Engineer | source: Fixture board\n- [x] https://fixture.example/22 | Fixture Partial | Engineer | source: Fixture board\n');
  const rows = () => { const lines = fs.readFileSync(file, 'utf8').split('\n'), cols = resolveColumns(lines); return lines.map(line => parseTrackerRow(line, cols)).filter(Boolean); };
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ ...(process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : { channel: 'chrome' }), headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.addInitScript(() => localStorage.setItem('career-ops:first-score-seen', '1'));
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/api/clis', route => route.fulfill({ json: { clis: [{ id: 'fixture', installed: true }] } }));
  await page.route('**/api/runs/save', route => route.fulfill({ json: { ok: true } }));
  let mode = 'save', release;
  const requests = [];
  await page.route('**/api/run', async route => {
    const request = route.request().postDataJSON();
    requests.push(request);
    if (mode === 'fail') return route.fulfill({ status: 503, json: { error: 'Fictional AI failure; previous report kept.' } });
    if (mode === 'hold') await new Promise(resolve => { release = resolve; });
    const app = rows().find(row => String(row.num) === request.targetApplication);
    const result = await persistEvaluation({ spawnFn: spawn, execPath: process.execPath, root, coreRoot: codeRoot,
      markdown: report(app.company, request.input), url: request.input, today: '2026-10-28', evaluationSections: request.evaluationSections,
      targetApplication: { num: String(app.num), expectedCompany: app.company, expectedRole: app.role, expectedReport: app.report } });
    assert.equal(result.ok, true, result.error);
    await route.fulfill({ contentType: 'application/x-ndjson', body: JSON.stringify({ type: 'text', text: 'VERDICT: 4.2/5 — Fictional fixture' }) + '\n' + JSON.stringify({ type: 'done', reportN: Number(result.applicationN), tokens: 1 }) + '\n' });
  });
  await page.goto(`${origin.origin}/pipeline?tab=SKIP`);
  const skipped = page.locator('tbody tr').filter({ hasText: 'Fixture Skip' });
  await skipped.getByText('Not evaluated', { exact: true }).waitFor();
  await skipped.getByRole('button', { name: 'Evaluate', exact: true }).click();
  let modal = page.getByRole('dialog', { name: 'Evaluate', exact: true });
  await modal.getByText(/Your status and notes are preserved/).waitFor();
  await modal.getByRole('button', { name: 'Essentials', exact: true }).click();
  mode = 'hold';
  await modal.getByRole('button', { name: 'Start evaluation', exact: true }).click();
  await skipped.getByRole('link', { name: 'Evaluating…', exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('dialog[open]') === null);
  while (!release) await new Promise(resolve => setTimeout(resolve, 10));
  assert.equal(rows().find(row => row.num === 11).score, '—');
  release();
  await skipped.getByText('Partial evaluation', { exact: true }).waitFor();
  assert.deepEqual(requests[0].evaluationSections, ['summary']);
  assert.equal(rows().find(row => row.num === 11).status, 'SKIP');
  await page.goto(`${origin.origin}/pipeline?tab=APPLIED`);
  const partial = page.locator('tbody tr').filter({ hasText: 'Fixture Partial' });
  await partial.getByRole('button', { name: 'Complete full evaluation', exact: true }).waitFor();
  await partial.getByRole('link', { name: 'Fixture Partial', exact: true }).click();
  await page.waitForURL(/\/pipeline\/22\?/);
  await page.getByRole('heading', { name: 'Fixture Partial', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Complete full evaluation', exact: true }).click();
  modal = page.getByRole('dialog', { name: 'Complete full evaluation', exact: true });
  await modal.getByText(/Your earlier report is kept/).waitFor();
  mode = 'fail';
  await modal.getByRole('button', { name: 'Start full evaluation', exact: true }).click();
  await page.getByRole('link', { name: 'Evaluation failed · view details', exact: true }).waitFor();
  assert.equal(fs.readFileSync(path.join(root, 'reports/044-partial-2026-10-28.md'), 'utf8'), original);
  assert.equal(rows().find(row => row.num === 22).report, '[044](../reports/044-partial-2026-10-28.md)');
  mode = 'save';
  await page.getByRole('button', { name: 'Complete full evaluation', exact: true }).click();
  await modal.getByRole('button', { name: 'Start full evaluation', exact: true }).click();
  await page.getByText('Full evaluation', { exact: true }).first().waitFor();
  await page.getByRole('button', { name: 'Re-evaluate', exact: true }).waitFor();
  assert.deepEqual(requests.at(-1).evaluationSections, [...FULL_EVALUATION]);
  assert.equal(requests.at(-1).targetApplication, '22');
  assert.equal(rows().length, 2);
  assert.equal(rows().find(row => row.num === 22).status, 'Applied');
  assert.equal(rows().find(row => row.num === 22).notes, 'Keep partial note');
  assert.equal(fs.readFileSync(path.join(root, 'reports/044-partial-2026-10-28.md'), 'utf8'), original);
  await page.reload();
  await page.getByText('Full evaluation', { exact: true }).first().waitFor();
  // Actual route validation rejects stale/mismatched targets before any CLI runs.
  const badUrl = await page.request.post(`${origin.origin}/api/run`, { data: { kind: 'evaluate', input: 'https://fixture.example/other', cliId: 'nonexistent-fixture', targetApplication: '11' } });
  assert.equal(badUrl.status(), 409);
  const missing = await page.request.post(`${origin.origin}/api/run`, { data: { kind: 'evaluate', input: 'https://fixture.example/99', cliId: 'nonexistent-fixture', targetApplication: '99' } });
  assert.equal(missing.status(), 404);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: 'Re-evaluate', exact: true }).click();
  const reeval = page.getByRole('dialog', { name: 'Re-evaluate', exact: true });
  await reeval.waitFor();
  assert.equal(await reeval.evaluate(el => el.scrollWidth > el.clientWidth), false);
  if (process.env.EVALUATE_APPLICATION_SCREENSHOT) await page.screenshot({ path: process.env.EVALUATE_APPLICATION_SCREENSHOT });
  assert.deepEqual(errors, []);
});
