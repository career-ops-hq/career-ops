import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { liveServerSkip } from '../helpers/live-server.mjs';

test('move evaluated applications into Preparation and back through the existing status control', { skip: liveServerSkip('PREPARATION_TEST_URL', 'PREPARATION_TEST_ROOT'), timeout: 90000 }, async t => {
  const origin = new URL(process.env.PREPARATION_TEST_URL);
  assert.ok(['localhost', '127.0.0.1'].includes(origin.hostname));
  const root = fs.realpathSync(process.env.PREPARATION_TEST_ROOT);
  const relative = path.relative(fs.realpathSync(os.tmpdir()), root);
  assert.ok(relative && !relative.startsWith('..') && !path.isAbsolute(relative));
  assert.equal(fs.readFileSync(path.join(root, '.inline-status-fixture'), 'utf8').trim(), 'fictional-only');
  const tracker = path.join(root, 'data/applications.md');
  const initial = fs.readFileSync(tracker, 'utf8');
  const { chromium } = await import('playwright-core');
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  t.after(() => browser.close());
  const page = await browser.newPage();
  const row = () => page.locator('tbody tr').filter({ has: page.getByRole('link', { name: '#11', exact: true }) });
  await page.goto(`${origin.origin}/pipeline?tab=EVALUATED`);
  await row().getByRole('button', { name: /^Edit status/ }).click();
  await row().getByRole('combobox').selectOption('Preparation');
  await row().waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: /^PREPARATION 1$/ }).click();
  await page.waitForURL(/tab=PREPARATION/);
  await row().waitFor();
  await page.reload();
  await row().waitFor();
  assert.equal(fs.readFileSync(tracker, 'utf8'), initial.replace('| Fixture Alpha | Engineer | 4.2/5 | Evaluated |', '| Fixture Alpha | Engineer | 4.2/5 | Preparation |'));
  await row().getByRole('link', { name: 'Fixture Alpha', exact: true }).click();
  const status = page.getByRole('combobox', { name: 'status', exact: true });
  await status.waitFor();
  assert.equal(await status.inputValue(), 'Preparation');
  await status.selectOption('Evaluated');
  await page.getByText('saved', { exact: true }).waitFor();
  await page.reload();
  assert.equal(await status.inputValue(), 'Evaluated');
  assert.equal(fs.readFileSync(tracker, 'utf8'), initial);
  assert.equal(await page.getByRole('link', { name: /^Preparation/ }).count(), 0);
});
